static const Glyph* glyph(char c) {
    for (size_t i = 0; i < sizeof(k_font) / sizeof(k_font[0]); i++)
        if (k_font[i].ch == c) return &k_font[i];
    return NULL;
}

static void put(uint32_t* cv, int x, int y, uint32_t c) {
    if (x >= 0 && x < CANVAS_W && y >= 0 && y < CANVAS_H) cv[y * CANVAS_W + x] = c;
}

static void bitmap(uint32_t* cv, int x, int y, const char* const rows[7], uint32_t ink, int scale) {
    for (int pass = 0; pass < 2; pass++) {
        uint32_t c = pass ? ink : 0xFF000000u;
        int o = pass ? 0 : 1;
        for (int j = 0; j < 7; j++)
            for (int i = 0; i < 5; i++)
                if (rows[j][i] == '#')
                    for (int sy = 0; sy < scale; sy++)
                        for (int sx = 0; sx < scale; sx++)
                            put(cv, x + i * scale + sx + o, y + j * scale + sy + o, c);
    }
}

void ui_text(uint32_t* cv, int x, int y, const char* s, uint32_t ink, int scale) {
    for (; *s; s++, x += 6 * scale) {
        const Glyph* g = glyph(*s);
        if (g) bitmap(cv, x, y, g->rows, ink, scale);
    }
}

int ui_text_w(const char* s, int scale) { return ((int)strlen(s) * 6 - 1) * scale; }

void ui_skull(uint32_t* cv, int x, int y, uint32_t ink, int scale) { bitmap(cv, x, y, k_skull, ink, scale); }

void ui_fill(uint32_t* cv, int x0, int y0, int x1, int y1, uint32_t c) {
    for (int y = y0; y < y1; y++)
        for (int x = x0; x < x1; x++) put(cv, x, y, c);
}

void ui_box(uint32_t* cv, int x0, int y0, int x1, int y1) {
    for (int y = y0; y < y1; y++)
        for (int x = x0; x < x1; x++) {
            if (x < 0 || x >= CANVAS_W || y < 0 || y >= CANVAS_H) continue;
            uint32_t* p = &cv[y * CANVAS_W + x];
            bool edge = y == y0 || y == y1 - 1 || x == x0 || x == x1 - 1;
            *p = edge ? 0xFFB8B8B8u : 0xC0000000u;   /* the overlay is blended over the picture */
        }
}
