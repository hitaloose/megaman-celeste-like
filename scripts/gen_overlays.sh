#!/bin/sh
# Embed the CRT overlays (assets/overlays/*.png) into host/mm_overlays_data.h,
# so the program needs no image files next to it. Run again after changing a PNG:
#
#   sh scripts/gen_overlays.sh
set -e
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
exec python3 - "$ROOT" <<'EOF'
import sys, os
root = sys.argv[1]
# (menu name, file): the order of the OVERLAY option after OFF
items = [
    ("CRT",          "Perfect_CRT.png"),
    ("CRT 240P",     "Perfect_CRT-240p.png"),
    ("CRT NOFRAME",  "Perfect_CRT(noframe).png"),
    ("240P NOFRAME", "Perfect_CRT-240p(noframe).png"),
]
out = ["/* Generated by scripts/gen_overlays.sh from assets/overlays/ (see CREDITS.txt there). Don't edit. */",
       "#pragma once", ""]
for i, (_, f) in enumerate(items):
    data = open(os.path.join(root, "assets/overlays", f), "rb").read()
    out.append("/* %s */" % f)
    out.append("static const unsigned char k_overlay%d[%d] = {" % (i, len(data)))
    for j in range(0, len(data), 20):
        out.append("    " + ",".join("0x%02x" % b for b in data[j:j + 20]) + ",")
    out.append("};")
out.append("")
out.append("static const struct { const char* name; const unsigned char* png; unsigned size; } k_overlays[] = {")
for i, (name, _) in enumerate(items):
    out.append('    { "%s", k_overlay%d, sizeof(k_overlay%d) },' % (name, i, i))
out.append("};")
open(os.path.join(root, "host/mm_overlays_data.h"), "w").write("\n".join(out) + "\n")
EOF
